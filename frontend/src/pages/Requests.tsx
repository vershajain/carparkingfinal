import { CheckCircle2, Hourglass, ShieldCheck } from 'lucide-react';
import { useState } from 'react';
import { toast } from 'sonner';
import { Empty, ErrorBox, Loading, NeedLogin, PageHeader, UrgencyBadge } from '../components/common';
import { Badge } from '../components/ui/badge';
import { Button } from '../components/ui/button';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '../components/ui/card';
import { Input, Label, Select } from '../components/ui/input';
import { Table, TD, TH, THead, TR } from '../components/ui/table';
import { errMsg, post, put } from '../lib/api';
import { useAuth } from '../lib/auth';
import { fmtDate } from '../lib/format';
import { useLive } from '../lib/useLive';

const empty = { registration: '', vehicleType: 'car', expectedDurationMinutes: 60, urgencyClaim: 'normal', reservationId: '', preferredAreaCode: '', requiresAccessibleSlot: false, specialRequirements: '' };

export default function Requests() {
  const { data: reqs, error, loading, reload } = useLive<any[]>('/requests');
  const { data: areas } = useLive<any[]>('/areas');
  const { canOperate } = useAuth();
  const [f, setF] = useState<any>(empty);
  const [busy, setBusy] = useState(false);
  const [result, setResult] = useState<any>(null);
  const set = (k: string, v: any) => setF((x: any) => ({ ...x, [k]: v }));

  const submit = async () => {
    setBusy(true);
    try {
      const body: any = { ...f, expectedDurationMinutes: Number(f.expectedDurationMinutes) };
      for (const k of ['reservationId', 'preferredAreaCode', 'specialRequirements']) if (!body[k]) delete body[k];
      const { data, message } = await post('/requests', body);
      setResult({ ok: true, data, message });
      toast.success(data.allocated ? `Allocated ${data.request.allocation?.slotCode}` : 'Request queued');
      reload();
    } catch (e) { setResult({ ok: false, message: errMsg(e) }); toast.error(errMsg(e)); }
    finally { setBusy(false); }
  };

  const [v, setV] = useState<any>({ registration: '', vehicleType: 'car', priorityCategory: 'emergency', needsAccessibleSlot: false, note: '' });
  const verify = async () => {
    try { await put(`/vehicles/${encodeURIComponent(v.registration)}`, { vehicleType: v.vehicleType, priorityCategory: v.priorityCategory, needsAccessibleSlot: v.needsAccessibleSlot, note: v.note || undefined }); toast.success(`${v.registration}: ${v.priorityCategory} status verified`); }
    catch (e) { toast.error(errMsg(e)); }
  };

  return (
    <>
      <PageHeader title="Vehicle Requests" subtitle="Submitting a request validates it, queues it and runs the scheduler automatically - no Play button." />
      <div className="grid gap-4 lg:grid-cols-2">
        <Card>
          <CardHeader><CardTitle>New parking request</CardTitle><CardDescription>Request ID and arrival timestamp are generated by the server.</CardDescription></CardHeader>
          <CardContent>
            <form className="grid gap-3 sm:grid-cols-2" onSubmit={(e) => { e.preventDefault(); submit(); }}>
              <div><Label htmlFor="reg">Registration number</Label><Input id="reg" value={f.registration} onChange={(e) => set('registration', e.target.value)} placeholder="TN01AB1234" required /></div>
              <div><Label htmlFor="vt">Vehicle type</Label><Select id="vt" value={f.vehicleType} onChange={(e) => set('vehicleType', e.target.value)}>{['bike', 'car', 'suv', 'other'].map((t) => <option key={t}>{t}</option>)}</Select></div>
              <div><Label htmlFor="dur">Expected duration (minutes)</Label><Input id="dur" type="number" min={5} max={1440} value={f.expectedDurationMinutes} onChange={(e) => set('expectedDurationMinutes', e.target.value)} required /></div>
              <div><Label htmlFor="urg">Urgency (claim only)</Label><Select id="urg" value={f.urgencyClaim} onChange={(e) => set('urgencyClaim', e.target.value)}><option value="normal">Normal</option><option value="priority">Priority</option><option value="emergency">Emergency</option></Select>
                <p className="mt-1 text-xs text-slate-500">Never trusted: only operator-verified status counts.</p></div>
              <div><Label htmlFor="rsv">Reservation ID (optional)</Label><Input id="rsv" value={f.reservationId} onChange={(e) => set('reservationId', e.target.value)} placeholder="RSV-000001" /></div>
              <div><Label htmlFor="area">Preferred area (optional)</Label><Select id="area" value={f.preferredAreaCode} onChange={(e) => set('preferredAreaCode', e.target.value)}><option value="">No preference</option>{areas?.map((a) => <option key={a._id} value={a.code}>{a.code} - {a.name}</option>)}</Select></div>
              <div className="sm:col-span-2"><Label htmlFor="sp">Special requirements (optional)</Label><Input id="sp" value={f.specialRequirements} onChange={(e) => set('specialRequirements', e.target.value)} maxLength={200} /></div>
              <label className="flex items-center gap-2 text-sm sm:col-span-2"><input type="checkbox" checked={f.requiresAccessibleSlot} onChange={(e) => set('requiresAccessibleSlot', e.target.checked)} />Needs an accessible slot (honoured only if an operator has verified it)</label>
              <Button type="submit" disabled={busy} className="sm:col-span-2">Submit request</Button>
            </form>
            {result && (
              <div role="status" className={`mt-4 rounded-lg border p-3 text-sm ${result.ok ? (result.data.allocated ? 'border-green-300 bg-green-50' : 'border-amber-300 bg-amber-50') : 'border-red-300 bg-red-50'}`}>
                {result.ok ? (<>
                  <p className="flex items-center gap-1 font-semibold">{result.data.allocated ? <CheckCircle2 className="h-4 w-4" /> : <Hourglass className="h-4 w-4" />}{result.data.allocated ? 'Slot allocated' : 'Waiting in queue'} - {result.data.request.requestId}</p>
                  <ul className="ml-5 mt-1 list-disc">{result.data.messages.map((m: string) => <li key={m}>{m}</li>)}</ul>
                  {result.data.allocated && <p className="mt-1">Why: {result.data.request.allocation?.vehicleReason}</p>}
                </>) : <p>{result.message}</p>}
              </div>
            )}
          </CardContent>
        </Card>
        <Card>
          <CardHeader><CardTitle className="flex items-center gap-1"><ShieldCheck className="h-4 w-4" />Verify priority status (operators)</CardTitle><CardDescription>Emergency/priority status is authorised here, with the verifier recorded in the audit log.</CardDescription></CardHeader>
          <CardContent>
            {!canOperate ? <NeedLogin /> : (
              <form className="grid gap-3 sm:grid-cols-2" onSubmit={(e) => { e.preventDefault(); verify(); }}>
                <div><Label htmlFor="vr">Registration</Label><Input id="vr" value={v.registration} onChange={(e) => setV({ ...v, registration: e.target.value })} required /></div>
                <div><Label htmlFor="vvt">Vehicle type</Label><Select id="vvt" value={v.vehicleType} onChange={(e) => setV({ ...v, vehicleType: e.target.value })}>{['bike', 'car', 'suv', 'other'].map((t) => <option key={t}>{t}</option>)}</Select></div>
                <div><Label htmlFor="vc">Verified category</Label><Select id="vc" value={v.priorityCategory} onChange={(e) => setV({ ...v, priorityCategory: e.target.value })}><option>normal</option><option>priority</option><option>emergency</option></Select></div>
                <div><Label htmlFor="vn">Note</Label><Input id="vn" value={v.note} onChange={(e) => setV({ ...v, note: e.target.value })} placeholder="e.g. ambulance #4" /></div>
                <label className="flex items-center gap-2 text-sm sm:col-span-2"><input type="checkbox" checked={v.needsAccessibleSlot} onChange={(e) => setV({ ...v, needsAccessibleSlot: e.target.checked })} />Verified: needs accessible slot</label>
                <Button type="submit" className="sm:col-span-2">Save verification</Button>
              </form>
            )}
          </CardContent>
        </Card>
      </div>
      <Card className="mt-4">
        <CardHeader><CardTitle>Recent requests</CardTitle></CardHeader>
        <CardContent>
          {loading ? <Loading /> : error ? <ErrorBox message={error} /> : !reqs?.length ? <Empty>No requests yet. Submit one above.</Empty> : (
            <Table><THead><TR><TH>Request</TH><TH>Vehicle</TH><TH>Type</TH><TH>Urgency</TH><TH>Duration</TH><TH>Arrived</TH><TH>Status</TH><TH>Score</TH></TR></THead>
              <tbody>{reqs.slice(0, 30).map((r) => (
                <TR key={r._id}><TD className="font-mono">{r.requestId}</TD><TD className="font-mono">{r.registration}</TD><TD>{r.vehicleType}</TD><TD><UrgencyBadge urgency={r.urgency} /></TD><TD>{r.expectedDurationMinutes} min</TD><TD>{fmtDate(r.arrivalTime)}</TD>
                  <TD><Badge tone={r.status === 'allocated' ? 'green' : r.status === 'waiting' ? 'amber' : 'slate'}>{r.status}</Badge></TD><TD>{r.priorityScore ?? '-'}</TD></TR>))}</tbody></Table>
          )}
        </CardContent>
      </Card>
    </>
  );
}
